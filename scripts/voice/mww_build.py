"""Build the microWakeWord detector helper (native/mww/mww_detect.cc), host or ARM32.

    python -m scripts.voice.mww_build --tflm TFLM --flatbuffers FB --frontend PMF \
        --model komp=/PRIVATE/komp.tflite --target arm-linux-musleabihf \
        --zig /PRIVATE/zig --out /PRIVATE/mww-detect-armhf

Stdlib only. Sources are owner-downloaded and pinned (docs/MICRO_WAKE_WORD.md):
TFLM = tensorflow/tflite-micro tree, FB = flatbuffers tree, PMF = pymicro-features
2.0.2 sdist (microfrontend + patched kissfft, the extractor used in training).
Model weights are compiled in and never written into this checkout. Prints the
artifact SHA-256; record it and inspect the ELF before any transfer proposal.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[2] / "src/alice_mcp/native/mww" / "mww_detect.cc"
TARGETS = {"native", "x86_64-linux-musl", "arm-linux-musleabihf"}
MODEL_LIMIT = 1024 * 1024
NAME = re.compile(r"[a-z][a-z0-9_]{0,31}")
FRONTEND = ["kiss_fft_int16.cc", "fft.cc", "fft_util.cc", "filterbank.cc",
            "filterbank_util.cc", "frontend.cc", "frontend_util.cc", "log_lut.cc",
            "log_scale.cc", "log_scale_util.cc", "noise_reduction.cc",
            "noise_reduction_util.cc", "pcan_gain_control.cc", "pcan_gain_control_util.cc",
            "window.cc", "window_util.cc"]
TFLM_DIRS = ["", "arena_allocator", "memory_planner", "kernels", "kernels/internal",
             "kernels/internal/reference"]
TFLM_SKIP = {"fake_micro_context.cc", "mock_micro_graph.cc", "kernel_runner.cc",
             "test_helpers.cc", "test_helper_custom_ops.cc", "recording_micro_allocator.cc"}
FLAGS = ["-std=c++17", "-fno-rtti", "-fno-exceptions", "-fno-threadsafe-statics",
         "-fno-unwind-tables", "-fno-asynchronous-unwind-tables", "-ffunction-sections",
         "-fdata-sections", "-DTFLM_REMOVE_VIRTUAL_DELETE", "-DTF_LITE_DISABLE_X86_NEON",
         "-DTF_LITE_STATIC_MEMORY", "-DNDEBUG", "-DFLATBUFFERS_LOCALE_INDEPENDENT=0",
         "-DFIXED_POINT=16", "-O2", "-w"]


def model_header(models: list[tuple[str, bytes]]) -> str:
    """C++ header embedding each model; names are validated identifiers."""
    if not 1 <= len(models) <= 8 or len({name for name, _ in models}) != len(models):
        raise ValueError("expected 1–8 uniquely named models")
    lines = ["/* Generated by scripts.voice.mww_build; do not commit. */"]
    for index, (name, data) in enumerate(models):
        if not NAME.fullmatch(name) or not 0 < len(data) <= MODEL_LIMIT:
            raise ValueError("model name or size outside bounds")
        body = ",".join(str(b) for b in data)
        lines.append(f"alignas(16) static const unsigned char kModel{index}[] = {{{body}}};")
    entries = ",".join(
        f'{{"{name}",kModel{i},{len(data)}u,"{hashlib.sha256(data).hexdigest()}"}}'
        for i, (name, data) in enumerate(models))
    lines.append(f"static const MwwModel kModels[] = {{{entries}}};")
    lines.append(f"static const int kModelCount = {len(models)};")
    return "\n".join(lines) + "\n"


def sources(tflm: Path, frontend: Path) -> list[Path]:
    found = [frontend / "tensorflow/lite/experimental/microfrontend/lib" / f for f in FRONTEND]
    for sub in TFLM_DIRS:
        directory = tflm / "tensorflow/lite/micro" / sub
        found += sorted(p for p in directory.glob("*.cc")
                        if not p.name.endswith("_test.cc") and p.name not in TFLM_SKIP)
    return found


def compiler(target: str, zig: Path | None) -> list[str]:
    if target == "native":
        cxx = shutil.which("c++")
        if not cxx:
            raise SystemExit("no host C++ compiler")
        return [cxx]
    if zig is None:
        raise SystemExit("--zig is required for cross targets")
    return [str(zig), "c++", "-target", target]


def build(tflm: Path, flatbuffers: Path, frontend: Path, models: list[tuple[str, bytes]],
          target: str, zig: Path | None, out: Path, jobs: int) -> dict[str, object]:
    cxx = compiler(target, zig)
    with tempfile.TemporaryDirectory(prefix="mww-build-") as tmp:
        work = Path(tmp)
        (work / "mww_models.h").write_text(model_header(models), encoding="ascii")
        includes = [f"-I{work}", f"-I{tflm}", f"-I{flatbuffers / 'include'}", f"-I{frontend}",
                    f"-I{frontend / 'kissfft'}"]
        env = dict(os.environ)
        env.setdefault("ZIG_GLOBAL_CACHE_DIR", str(work / "zig-cache"))
        env["ZIG_LOCAL_CACHE_DIR"] = str(work / "zig-cache")
        units = [*sources(tflm, frontend), SOURCE]

        def compile_one(item: tuple[int, Path]) -> Path:
            index, source = item
            obj = work / f"{index:04d}.o"
            subprocess.run([*cxx, *FLAGS, *includes, "-c", str(source), "-o", str(obj)],
                           check=True, env=env)
            return obj

        with ThreadPoolExecutor(jobs) as pool:
            objects = list(pool.map(compile_one, enumerate(units)))
        subprocess.run([*cxx, "-static", "-s", "-Wl,--gc-sections", *map(str, objects),
                        "-o", str(out)], check=True, env=env)
    data = out.read_bytes()
    return {"artifact": out.name, "target": target, "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "models": [{"name": n, "sha256": hashlib.sha256(d).hexdigest()} for n, d in models]}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tflm", type=Path, required=True)
    parser.add_argument("--flatbuffers", type=Path, required=True)
    parser.add_argument("--frontend", type=Path, required=True)
    parser.add_argument("--model", action="append", required=True, help="NAME=PATH")
    parser.add_argument("--target", choices=sorted(TARGETS), default="native")
    parser.add_argument("--zig", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 1)
    args = parser.parse_args(argv)
    models = []
    for item in args.model:
        name, _, path = item.partition("=")
        data = Path(path).read_bytes()[:MODEL_LIMIT + 1]
        models.append((name, data))
    try:
        result = build(args.tflm, args.flatbuffers, args.frontend, models, args.target,
                       args.zig, args.out, max(1, args.jobs))
    except (ValueError, subprocess.CalledProcessError) as error:
        print(json.dumps({"status": "failed", "error": type(error).__name__}), file=sys.stderr)
        return 1
    print(json.dumps(result))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
